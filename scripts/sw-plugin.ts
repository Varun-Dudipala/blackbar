// Writes dist/sw.js at build time with the exact list of files the build
// produced, so the app shell (HTML, scripts, styles, fonts) loads with no network.
import type { Plugin } from 'vite'
import { createHash } from 'node:crypto'

export function serviceWorker(): Plugin {
  return {
    name: 'blackbar:service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map'))
      const assets = ['./', ...files.map((f) => `./${f}`), './favicon.svg', './manifest.webmanifest', './icon-192.png', './icon-512.png']
      const version = createHash('sha256').update(files.sort().join('|')).digest('hex').slice(0, 12)
      const source = `// Generated by scripts/sw-plugin.ts. Caches the app shell only; it never sees letter text.
const CACHE = 'blackbar-${version}'
const ASSETS = ${JSON.stringify(assets)}
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()))
})
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('blackbar-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})
self.addEventListener('fetch', (event) => {
  const req = event.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)
  if (url.origin !== self.location.origin) return
  if (req.mode === 'navigate') {
    event.respondWith(fetch(req).catch(() => caches.match('./', { cacheName: CACHE, ignoreVary: true })))
    return
  }
  event.respondWith(caches.match(req, { cacheName: CACHE, ignoreVary: true }).then((hit) => hit || fetch(req)))
})
`
      this.emitFile({ type: 'asset', fileName: 'sw.js', source })
    },
  }
}
